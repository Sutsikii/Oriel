using System.Security.Cryptography;
using System.Text;

namespace Oriel.Build;

/// <summary>What an installer is made of, from the app's project.</summary>
/// <param name="AppName">The app's name, as users see it: the folder, the shortcut, the apps list.</param>
/// <param name="AppVersion">The version, as in <c>1.2.0</c>.</param>
/// <param name="AppId">Identifies the app across versions, so that one replaces the other. A GUID, with or without braces.</param>
/// <param name="Publisher">Who makes the app, shown in the apps list.</param>
/// <param name="Executable">The file name of the app's executable, in <paramref name="PublishDirectory"/>.</param>
/// <param name="PublishDirectory">The published app: every file in it is installed, debug symbols aside.</param>
/// <param name="OutputDirectory">Where the installer is written.</param>
/// <param name="Icon">The icon of the installer, or null for Inno Setup's.</param>
/// <param name="Languages">The languages of the wizard, by the names of Inno Setup's message files: <c>english</c>, <c>french</c>…</param>
/// <param name="UrlSchemes">The schemes of links the app opens, such as <c>myapp</c> for <c>myapp://…</c>.</param>
/// <param name="FileTypes">The extensions of the files the app opens, such as <c>.note</c>.</param>
/// <param name="Signed">
/// Whether Inno Setup signs the installer and the uninstaller, with the
/// sign tool <c>oriel</c> the compiler is given (<see cref="InnoSetupScript.SignToolArgument"/>).
/// </param>
internal sealed record InstallerSettings(
    string AppName,
    string AppVersion,
    string AppId,
    string Publisher,
    string Executable,
    string PublishDirectory,
    string OutputDirectory,
    string? Icon,
    IReadOnlyList<string> Languages,
    IReadOnlyList<string>? UrlSchemes = null,
    IReadOnlyList<string>? FileTypes = null,
    bool Signed = false);

/// <summary>
/// Writes the Inno Setup script of an Oriel app's installer: a per-user
/// install without administrator rights, a Start menu shortcut, an
/// uninstaller, and a check for the WebView2 Runtime. docs/build.md
/// describes what it does.
/// </summary>
internal static class InnoSetupScript
{
    // Names AppIds derived from app names (an RFC 4122 version 5 UUID namespace).
    private static readonly Guid s_namespace = new("8b7a1f2e-4c3d-5e6f-9a0b-1c2d3e4f5a6b");

    public static string Create(InstallerSettings s)
    {
        if (s.Languages.Count == 0)
            throw new ArgumentException("An installer needs a language.", nameof(s));
        var publish = s.PublishDirectory.TrimEnd('\\', '/');
        var sb = new StringBuilder();
        sb.Append("; Generated by Oriel from the app's project. Do not edit: set the Oriel* properties instead.\n\n");

        sb.Append("[Setup]\n");
        // Braces start constants in Inno Setup: an AppId's opening one is doubled.
        Line(sb, "AppId", "{{" + NormalizeId(s.AppId) + "}");
        Line(sb, "AppName", Constant(s.AppName));
        Line(sb, "AppVersion", s.AppVersion);
        Line(sb, "AppVerName", Constant(s.AppName + " " + s.AppVersion));
        Line(sb, "AppPublisher", Constant(s.Publisher));
        Line(sb, "VersionInfoVersion", NumericVersion(s.AppVersion));
        sb.Append("; Per user, without administrator rights: %LOCALAPPDATA%\\Programs.\n");
        Line(sb, "PrivilegesRequired", "lowest");
        Line(sb, "PrivilegesRequiredOverridesAllowed", "dialog");
        Line(sb, "DefaultDirName", "{autopf}\\" + Constant(s.AppName));
        Line(sb, "DefaultGroupName", Constant(s.AppName));
        Line(sb, "DisableProgramGroupPage", "yes");
        Line(sb, "UninstallDisplayIcon", "{app}\\" + Constant(s.Executable));
        Line(sb, "UninstallDisplayName", Constant(s.AppName));
        if (s.Icon is not null)
            Line(sb, "SetupIconFile", s.Icon);
        Line(sb, "WizardStyle", "modern");
        Line(sb, "Compression", "lzma2/ultra");
        Line(sb, "SolidCompression", "yes");
        Line(sb, "ArchitecturesAllowed", "x64compatible");
        Line(sb, "ArchitecturesInstallIn64BitMode", "x64compatible");
        Line(sb, "MinVersion", "10.0.17763");
        if (s.Signed)
        {
            Line(sb, "SignTool", "oriel");
            Line(sb, "SignedUninstaller", "yes");
        }
        Line(sb, "OutputDir", s.OutputDirectory);
        Line(sb, "OutputBaseFilename", FileName(s.AppName) + "-Setup-" + s.AppVersion);
        if (s.FileTypes is { Count: > 0 })
            Line(sb, "ChangesAssociations", "yes");

        sb.Append("\n[Languages]\n");
        foreach (var language in s.Languages)
        {
            var messages = language == "english" ? "compiler:Default.isl" : $"compiler:Languages\\{Capitalize(language)}.isl";
            sb.Append($"Name: {Quote(language)}; MessagesFile: {Quote(messages)}\n");
        }

        sb.Append("\n[Tasks]\n");
        sb.Append("Name: \"desktopicon\"; Description: \"{cm:CreateDesktopIcon}\"; GroupDescription: \"{cm:AdditionalIcons}\"; Flags: unchecked\n");

        sb.Append("\n[Files]\n");
        sb.Append($"Source: {Quote(publish + "\\*")}; DestDir: \"{{app}}\"; Excludes: \"*.pdb\"; Flags: ignoreversion recursesubdirs createallsubdirs\n");

        sb.Append("\n[Icons]\n");
        sb.Append($"Name: {Quote("{autoprograms}\\" + Constant(s.AppName))}; Filename: {Quote("{app}\\" + Constant(s.Executable))}\n");
        sb.Append($"Name: {Quote("{autodesktop}\\" + Constant(s.AppName))}; Filename: {Quote("{app}\\" + Constant(s.Executable))}; Tasks: desktopicon\n");

        sb.Append("\n[Run]\n");
        sb.Append($"Filename: {Quote("{app}\\" + Constant(s.Executable))}; Description: {Quote("{cm:LaunchProgram," + Constant(s.AppName).Replace("&", "&&").Replace(",", "%2c") + "}")}; Flags: nowait postinstall skipifsilent\n");

        Registry(sb, s);

        sb.Append("\n[UninstallDelete]\n");
        sb.Append("; The webview's data; the app's own data, in %APPDATA%, is the user's and stays.\n");
        sb.Append($"Type: filesandordirs; Name: {Quote("{localappdata}\\" + Constant(s.AppName) + "\\WebView")}\n");
        sb.Append($"Type: dirifempty; Name: {Quote("{localappdata}\\" + Constant(s.AppName))}\n");

        sb.Append(WebView2Check);
        return sb.ToString();
    }

    /// <summary>
    /// The keys that make links of the app's schemes, and its files, open
    /// with it: under HKA, the user's classes for a per-user install, and
    /// removed with the app. Files are offered in Open with (OpenWithProgids):
    /// Windows asks the person before making the app their default.
    /// </summary>
    private static void Registry(StringBuilder sb, InstallerSettings s)
    {
        var schemes = s.UrlSchemes ?? [];
        var types = s.FileTypes ?? [];
        if (schemes.Count == 0 && types.Count == 0)
            return;
        var exe = "{app}\\" + Constant(s.Executable);
        var open = "\"\"" + exe + "\"\" \"\"%1\"\"";
        sb.Append("\n[Registry]\n");
        foreach (var scheme in schemes)
        {
            var key = "Software\\Classes\\" + scheme;
            sb.Append($"Root: HKA; Subkey: {Quote(key)}; ValueType: string; ValueName: \"\"; ValueData: {Quote("URL:" + Constant(s.AppName))}; Flags: uninsdeletekey\n");
            sb.Append($"Root: HKA; Subkey: {Quote(key)}; ValueType: string; ValueName: \"URL Protocol\"; ValueData: \"\"\n");
            sb.Append($"Root: HKA; Subkey: {Quote(key + "\\DefaultIcon")}; ValueType: string; ValueName: \"\"; ValueData: {Quote(exe + ",0")}\n");
            sb.Append($"Root: HKA; Subkey: {Quote(key + "\\shell\\open\\command")}; ValueType: string; ValueName: \"\"; ValueData: \"{open}\"\n");
        }
        foreach (var type in types)
        {
            var progId = FileName(s.AppName) + type;
            var key = "Software\\Classes\\" + progId;
            sb.Append($"Root: HKA; Subkey: {Quote("Software\\Classes\\" + type + "\\OpenWithProgids")}; ValueType: string; ValueName: {Quote(progId)}; ValueData: \"\"; Flags: uninsdeletevalue\n");
            sb.Append($"Root: HKA; Subkey: {Quote(key)}; ValueType: string; ValueName: \"\"; ValueData: {Quote(Constant(s.AppName))}; Flags: uninsdeletekey\n");
            sb.Append($"Root: HKA; Subkey: {Quote(key + "\\DefaultIcon")}; ValueType: string; ValueName: \"\"; ValueData: {Quote(exe + ",0")}\n");
            sb.Append($"Root: HKA; Subkey: {Quote(key + "\\shell\\open\\command")}; ValueType: string; ValueName: \"\"; ValueData: \"{open}\"\n");
        }
    }

    /// <summary>
    /// The compiler's argument that defines the sign tool <c>oriel</c> of
    /// <paramref name="command"/>, whose <c>{file}</c> is the file to sign,
    /// in Inno Setup's terms: <c>$f</c> the file (quoted by Inno Setup),
    /// <c>$q</c> a quote, <c>$$</c> a dollar.
    /// </summary>
    public static string SignToolArgument(string command) =>
        "/Soriel=" + command.Replace("$", "$$").Replace("\"", "$q").Replace("{file}", "$f");

    /// <summary>Whether <paramref name="scheme"/> may be a link's scheme the app takes: letters first, then letters, digits, <c>+</c>, <c>-</c> and <c>.</c>.</summary>
    public static bool IsScheme(string scheme) =>
        scheme.Length > 1 && IsLetter(scheme[0]) && scheme.All(c => IsLetterOrDigit(c) || c is '+' or '-' or '.')
        && !new[] { "http", "https", "file", "mailto", "ftp", "javascript", "data", "about", "ms-settings" }.Contains(scheme.ToLowerInvariant());

    private static bool IsLetter(char c) => c is >= 'a' and <= 'z' or >= 'A' and <= 'Z';

    private static bool IsLetterOrDigit(char c) => IsLetter(c) || c is >= '0' and <= '9';

    /// <summary>Whether <paramref name="type"/> is an extension, as <c>.note</c>.</summary>
    public static bool IsFileType(string type) =>
        type.Length > 1 && type[0] == '.' && type.Skip(1).All(c => IsLetterOrDigit(c) || c is '-' or '_');

    /// <summary>
    /// An AppId of <paramref name="appName"/>, the same on every build: a
    /// version 5 UUID of the name. Renaming the app gives another AppId, so
    /// apps set theirs once they ship.
    /// </summary>
    public static Guid StableAppId(string appName)
    {
        var ns = s_namespace.ToByteArray();
        SwapByteOrder(ns);
        byte[] hash;
        using (var sha1 = SHA1.Create())
            hash = sha1.ComputeHash(ns.Concat(Encoding.UTF8.GetBytes(appName)).ToArray());
        var bytes = new byte[16];
        Array.Copy(hash, bytes, 16);
        bytes[6] = (byte)((bytes[6] & 0x0F) | 0x50); // version 5
        bytes[8] = (byte)((bytes[8] & 0x3F) | 0x80); // RFC 4122 variant
        SwapByteOrder(bytes);
        return new Guid(bytes);
    }

    /// <summary><paramref name="name"/> made safe for a file name.</summary>
    public static string FileName(string name)
    {
        var invalid = Path.GetInvalidFileNameChars();
        var sb = new StringBuilder();
        foreach (var c in name)
            sb.Append(invalid.Contains(c) || char.IsWhiteSpace(c) ? '-' : c);
        return sb.ToString().Trim('-');
    }

    /// <summary>Windows wants a version of numbers only: <c>1.2.0-beta</c> is <c>1.2.0</c>.</summary>
    public static string NumericVersion(string version)
    {
        var parts = version.Split('-', '+')[0].Split('.');
        var numbers = parts.Take(4).Select(p => int.TryParse(p, out var n) && n >= 0 ? n : 0).ToList();
        while (numbers.Count < 2)
            numbers.Add(0);
        return string.Join(".", numbers);
    }

    private static string NormalizeId(string id)
    {
        if (!Guid.TryParse(id, out var guid))
            throw new ArgumentException($"The AppId '{id}' is not a GUID.");
        return guid.ToString("D").ToUpperInvariant();
    }

    private static void Line(StringBuilder sb, string name, string value) =>
        sb.Append(name).Append('=').Append(value).Append('\n');

    /// <summary>A value in double quotes, as Inno Setup's parameters take them.</summary>
    private static string Quote(string value) => "\"" + value.Replace("\"", "\"\"") + "\"";

    /// <summary>Text where Inno Setup reads constants: a brace starts one, so a literal brace is doubled.</summary>
    private static string Constant(string text) => text.Replace("{", "{{");

    private static string Capitalize(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s.Substring(1);

    /// <summary>A GUID's first three fields are little-endian in its bytes; UUIDs are big-endian.</summary>
    private static void SwapByteOrder(byte[] g)
    {
        Array.Reverse(g, 0, 4);
        Array.Reverse(g, 4, 2);
        Array.Reverse(g, 6, 2);
    }

    // Pages show in the WebView2 Runtime, which Windows 11 has. Without it,
    // the installer offers its download instead of installing an app that
    // cannot run.
    private const string WebView2Check = """

        [Code]
        function WebView2Installed: Boolean;
        var
          Version: String;
        begin
          Result :=
            (RegQueryStringValue(HKLM, 'SOFTWARE\WOW6432Node\Microsoft\EdgeUpdate\Clients\{F3017226-FE2A-4295-8BDF-00C3A9A7E4C5}', 'pv', Version) and (Version <> '') and (Version <> '0.0.0.0')) or
            (RegQueryStringValue(HKCU, 'Software\Microsoft\EdgeUpdate\Clients\{F3017226-FE2A-4295-8BDF-00C3A9A7E4C5}', 'pv', Version) and (Version <> '') and (Version <> '0.0.0.0'));
        end;

        function InitializeSetup: Boolean;
        var
          Code: Integer;
        begin
          Result := True;
          if not WebView2Installed then
          begin
            if MsgBox('This app needs the Microsoft Edge WebView2 Runtime, which is not installed.' + #13#10 + 'Open its download page?', mbConfirmation, MB_YESNO) = IDYES then
              ShellExec('open', 'https://go.microsoft.com/fwlink/p/?LinkId=2124703', '', '', SW_SHOWNORMAL, ewNoWait, Code);
            Result := False;
          end;
        end;

        """;
}
