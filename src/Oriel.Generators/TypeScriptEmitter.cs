namespace Oriel.Generators;

/// <summary>
/// Writes the TypeScript client of a project's services: their types, and an
/// object per service whose methods call C#. The file needs nothing but the
/// page runtime Oriel injects, so it is a plain module any bundler takes.
/// </summary>
internal static class TypeScriptEmitter
{
    private static readonly HashSet<string> s_reserved = new(StringComparer.Ordinal)
    {
        "arguments", "await", "break", "case", "catch", "class", "const", "continue", "debugger", "default",
        "delete", "do", "else", "enum", "eval", "export", "extends", "false", "finally", "for", "function",
        "if", "implements", "import", "in", "instanceof", "interface", "let", "new", "null", "package",
        "private", "protected", "public", "return", "static", "super", "switch", "this", "throw", "true",
        "try", "typeof", "var", "void", "while", "with", "yield",
    };

    public static string Emit(Project project, string assembly)
    {
        var names = project.Enums.ToDictionary(e => e.Id, e => e.TypeScript);
        foreach (var o in project.Objects)
            names[o.Id] = o.TypeScript;

        var w = new SourceWriter("  ");
        w.Line($"// Generated by Oriel from the [Service] classes of {assembly}. Do not edit.");
        w.Line("/* eslint-disable */");
        w.Line();
        Runtime(w, project);

        if (project.Enums.Count + project.Objects.Count + project.Errors.Count > 0)
        {
            w.Line();
            w.Line("// ---- Types ----");
            foreach (var definition in Definitions(project))
            {
                w.Line();
                definition(w, names);
            }
        }

        w.Line();
        w.Line("// ---- Services ----");
        foreach (var service in project.Services)
        {
            w.Line();
            Service(w, service, names);
        }

        w.Line();
        w.Line("// ---- Window ----");
        Window(w);
        return w.ToString();
    }

    private static void Runtime(SourceWriter w, Project project)
    {
        w.Line("class CallErrorBase extends Error {");
        using (w.Indent())
        {
            w.Line("/** The method that failed, as \"Service.Method\". */");
            w.Line("readonly method: string;");
            w.Line("/** The code of a [ServiceError] exception, or null. */");
            w.Line("readonly code: string | null;");
            w.Line("/** The public properties of a [ServiceError] exception, or null. */");
            w.Line("readonly data: unknown;");
            w.Line();
            w.Line("constructor(method: string, message: string, code: string | null = null, data: unknown = null) {");
            using (w.Indent())
            {
                w.Line("super(message);");
                w.Line("this.name = \"CallError\";");
                w.Line("this.method = method;");
                w.Line("this.code = code;");
                w.Line("this.data = code === null ? null : data;");
            }
            w.Line("}");
        }
        w.Line("}");
        w.Line();
        // A union, so that checking err.code narrows err.data. A class cannot
        // be one, so CallError is a type and a constructor of the same name.
        var members = project.Errors.Select(e => $"{{ readonly code: \"{e.Code}\"; readonly data: {e.TypeScript} }}")
            .Concat(["{ readonly code: null; readonly data: null }"]);
        w.Line("/**");
        w.Line(" * The error a call rejects with: the C# method threw, or its arguments did not fit its parameters.");
        w.Line(" * Errors of [ServiceError] exceptions have their code, which tells their data's type.");
        w.Line(" */");
        w.Line($"export type CallError = CallErrorBase & ({string.Join(" | ", members)});");
        w.Line("export const CallError = CallErrorBase as unknown as {");
        using (w.Indent())
        {
            w.Line("new (method: string, message: string, code?: string | null, data?: unknown): CallError;");
            w.Line("readonly prototype: CallError;");
        }
        w.Line("};");
        w.Line();
        w.Line("interface Bridge {");
        using (w.Indent())
        {
            w.Line("call(method: string, args: unknown[]): Promise<unknown>;");
            w.Line("on(event: string, listener: (payload: unknown) => void): () => void;");
            if (HasStreams(project))
                w.Line("stream(method: string, args: unknown[]): AsyncIterable<unknown>;");
        }
        w.Line("}");
        w.Line();
        w.Line("function bridge(): Bridge {");
        using (w.Indent())
        {
            w.Line("const runtime = (globalThis as { oriel?: Bridge }).oriel;");
            w.Line("if (!runtime) throw new Error(\"Oriel: window.oriel is missing; open this page in an Oriel window\");");
            w.Line("return runtime;");
        }
        w.Line("}");
        // Only the helpers the services use, for projects that refuse unused code.
        if (project.Services.Any(s => s.Methods.Any(m => m.Returns != Returns.Stream)))
            CallHelper(w);
        if (HasStreams(project))
            StreamHelper(w);
        if (project.Services.Any(s => s.Events.Count > 0))
            OnHelper(w);
    }

    /// <summary>What the page's window tells it, besides the services' events.</summary>
    private static void Window(SourceWriter w)
    {
        w.Line();
        w.Line("/**");
        w.Line(" * Fires when files are dropped on this window, with their full paths and where they were");
        w.Line(" * dropped, in CSS pixels of the page; the page's own drop event has their File objects.");
        w.Line(" * Returns a function that stops listening.");
        w.Line(" */");
        w.Line("export function onFilesDropped(listener: (drop: { paths: string[]; x: number; y: number }) => void): () => void {");
        using (w.Indent())
            w.Line("return bridge().on(\"oriel:filesDropped\", listener as (payload: unknown) => void);");
        w.Line("}");
    }

    private static void OnHelper(SourceWriter w)
    {
        w.Line();
        w.Line("function on<T>(event: string, listener: (payload: T) => void): () => void {");
        using (w.Indent())
            w.Line("return bridge().on(event, listener as (payload: unknown) => void);");
        w.Line("}");
    }

    private static void CallHelper(SourceWriter w)
    {
        w.Line();
        w.Line("async function call<T>(method: string, ...args: unknown[]): Promise<T> {");
        using (w.Indent())
        {
            w.Line("// Arguments left out stay out, so that C# uses its defaults.");
            w.Line("while (args.length > 0 && args[args.length - 1] === undefined) args.pop();");
            w.Line("try {");
            using (w.Indent())
                w.Line("return (await bridge().call(method, args)) as T;");
            w.Line("} catch (err) {");
            using (w.Indent())
            {
                w.Line("if (err instanceof Error && err.name === \"CallError\") {");
                using (w.Indent())
                {
                    w.Line("const { code, data } = err as { code?: string | null; data?: unknown };");
                    w.Line("throw new CallError(method, err.message, code ?? null, data);");
                }
                w.Line("}");
                w.Line("throw err;");
            }
            w.Line("}");
        }
        w.Line("}");
    }

    private static bool HasStreams(Project project) =>
        project.Services.Any(s => s.Methods.Any(m => m.Returns == Returns.Stream));

    private static void StreamHelper(SourceWriter w)
    {
        w.Line();
        w.Line("function stream<T>(method: string, ...args: unknown[]): AsyncIterable<T> {");
        using (w.Indent())
        {
            w.Line("// Arguments left out stay out, so that C# uses its defaults.");
            w.Line("while (args.length > 0 && args[args.length - 1] === undefined) args.pop();");
            w.Line("return {");
            using (w.Indent())
            {
                w.Line("[Symbol.asyncIterator](): AsyncIterator<T> {");
                using (w.Indent())
                {
                    w.Line("const items = bridge().stream(method, args)[Symbol.asyncIterator]();");
                    w.Line("return {");
                    using (w.Indent())
                    {
                        w.Line("async next(): Promise<IteratorResult<T>> {");
                        using (w.Indent())
                        {
                            w.Line("try {");
                            using (w.Indent())
                                w.Line("return (await items.next()) as IteratorResult<T>;");
                            w.Line("} catch (err) {");
                            using (w.Indent())
                            {
                                w.Line("if (err instanceof Error && err.name === \"CallError\") {");
                                using (w.Indent())
                                {
                                    w.Line("const { code, data } = err as { code?: string | null; data?: unknown };");
                                    w.Line("throw new CallError(method, err.message, code ?? null, data);");
                                }
                                w.Line("}");
                                w.Line("throw err;");
                            }
                            w.Line("}");
                        }
                        w.Line("},");
                        w.Line("async return(): Promise<IteratorResult<T>> {");
                        using (w.Indent())
                            w.Line("return (await items.return!()) as IteratorResult<T>;");
                        w.Line("},");
                    }
                    w.Line("};");
                }
                w.Line("},");
            }
            w.Line("};");
        }
        w.Line("}");
    }

    /// <summary>The types, by TypeScript name, enums and objects mixed.</summary>
    private static IEnumerable<Action<SourceWriter, Dictionary<string, string>>> Definitions(Project project)
    {
        var all = project.Enums.Select(e => (Name: e.TypeScript, Write: (Action<SourceWriter, Dictionary<string, string>>)((w, _) => Enum(w, e))))
            .Concat(project.Objects.Select(o => (Name: o.TypeScript, Write: (Action<SourceWriter, Dictionary<string, string>>)((w, n) => Interface(w, o, n)))))
            .Concat(project.Errors.Select(e => (Name: e.TypeScript, Write: (Action<SourceWriter, Dictionary<string, string>>)((w, n) => ErrorData(w, e, n)))));
        return all.OrderBy(d => d.Name, StringComparer.Ordinal).Select(d => d.Write);
    }

    /// <summary>The data of a service error: <c>err.data</c> once <c>err.code</c> is its code.</summary>
    private static void ErrorData(SourceWriter w, ErrorDef e, Dictionary<string, string> names)
    {
        Doc(w, e.Doc.Summary);
        w.Line($"export interface {e.TypeScript} {{");
        using (w.Indent())
        {
            foreach (var p in e.Properties)
            {
                Doc(w, p.Doc.Summary);
                w.Line($"readonly {PropertyName(p.Json)}: {Type(p.Type, names)};");
            }
        }
        w.Line("}");
    }

    private static void Enum(SourceWriter w, EnumDef e)
    {
        Doc(w, e.Doc.Summary);
        var members = e.Members.Select(m => Quote(m.Json)).ToList();
        w.Line($"export type {e.TypeScript} = {(members.Count == 0 ? "never" : string.Join(" | ", members))};");
    }

    private static void Interface(SourceWriter w, ObjectDef o, Dictionary<string, string> names)
    {
        Doc(w, o.Doc.Summary);
        w.Line($"export interface {o.TypeScript} {{");
        using (w.Indent())
        {
            foreach (var p in o.Properties)
            {
                Doc(w, p.Doc.Summary);
                var readOnly = p.Assign == Assign.None ? "readonly " : "";
                w.Line($"{readOnly}{PropertyName(p.Json)}: {Type(p.Type, names)};");
            }
        }
        w.Line("}");
    }

    private static void Service(SourceWriter w, ServiceDef service, Dictionary<string, string> names)
    {
        Doc(w, service.Doc.Summary);
        w.Line($"export const {service.Name} = {{");
        using (w.Indent())
        {
            foreach (var method in service.Methods)
            {
                var page = method.Params.Where(p => p.Type is not null).ToList();
                var lines = new List<string>();
                if (method.Doc.Summary.Length > 0)
                    lines.Add(method.Doc.Summary);
                foreach (var p in page)
                {
                    var text = method.Doc.Param(p.Name);
                    if (text.Length > 0)
                        lines.Add($"@param {Parameter(p.Name)} {text}");
                }
                if (method.Doc.Returns.Length > 0)
                    lines.Add($"@returns {method.Doc.Returns}");
                Doc(w, lines);

                var parameters = page.Select(p => $"{Parameter(p.Name)}{(p.IsOptional ? "?" : "")}: {Type(p.Type!, names)}");
                var result = method.Result is null ? "void" : Type(method.Result, names);
                var arguments = new[] { Quote(service.Name + "." + method.CSharp) }.Concat(page.Select(p => Parameter(p.Name)));
                var (returned, helper) = method.Returns == Returns.Stream ? ("AsyncIterable", "stream") : ("Promise", "call");
                w.Line($"{method.TypeScript}({string.Join(", ", parameters)}): {returned}<{result}> {{");
                using (w.Indent())
                    w.Line($"return {helper}({string.Join(", ", arguments)});");
                w.Line("},");
            }
            foreach (var e in service.Events)
            {
                var lines = new List<string>();
                if (e.Doc.Summary.Length > 0)
                    lines.Add(e.Doc.Summary);
                lines.Add($"Calls listener with each payload of {service.Name}.{e.CSharp}; returns a function that stops listening.");
                Doc(w, lines);
                var payload = Type(e.Payload, names);
                w.Line($"{e.TypeScript}(listener: (payload: {payload}) => void): () => void {{");
                using (w.Indent())
                    w.Line($"return on<{payload}>({Quote(service.Name + "." + e.CSharp)}, listener);");
                w.Line("},");
            }
        }
        w.Line("} as const;");
    }

    /// <summary>The TypeScript of a type.</summary>
    internal static string Type(TypeRef t, IReadOnlyDictionary<string, string> names) => t.Kind switch
    {
        TypeKind.Primitive => t.TypeScript,
        TypeKind.Enum or TypeKind.Object => names[t.Name],
        TypeKind.NullableValue or TypeKind.NullableReference => $"{Type(t.Element!, names)} | null",
        TypeKind.Array or TypeKind.List => Wrap(Type(t.Element!, names)) + "[]",
        TypeKind.Dictionary => $"Record<string, {Type(t.Element!, names)}>",
        TypeKind.Binary => t.TypeScript,
        _ => throw new ArgumentOutOfRangeException(nameof(t)),
    };

    private static string Wrap(string type) => type.Contains("|") ? $"({type})" : type;

    private static void Doc(SourceWriter w, string text) =>
        Doc(w, text.Length == 0 ? new List<string>() : new List<string> { text });

    /// <summary>A TSDoc comment of <paramref name="paragraphs"/>, on one line when it fits.</summary>
    private static void Doc(SourceWriter w, List<string> paragraphs)
    {
        var lines = paragraphs.SelectMany(p => p.Replace("*/", "*\\/").Split('\n')).ToList();
        if (lines.Count == 0)
            return;
        if (lines.Count == 1 && !lines[0].StartsWith("@", StringComparison.Ordinal))
        {
            w.Line($"/** {lines[0]} */");
            return;
        }
        w.Line("/**");
        foreach (var line in lines)
            w.Line(line.Length == 0 ? " *" : $" * {line}");
        w.Line(" */");
    }

    private static string Parameter(string name) => s_reserved.Contains(name) ? name + "_" : name;

    private static string PropertyName(string name) =>
        name.Length > 0 && (char.IsLetter(name[0]) || name[0] == '_' || name[0] == '$') && name.All(c => char.IsLetterOrDigit(c) || c == '_' || c == '$')
            ? name
            : Quote(name);

    private static string Quote(string s) =>
        "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
