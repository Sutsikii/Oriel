namespace Oriel.Generators;

/// <summary>
/// Writes the C# half of the generated code: a dispatcher per service, the
/// JSON codecs of the types they use, and the module initializer that
/// registers the dispatchers with Oriel.
/// </summary>
internal static class CSharpEmitter
{
    private const string Json = "global::Oriel.Generated.Json";
    private const string Writer = "global::System.Text.Json.Utf8JsonWriter";
    private const string Element = "global::System.Text.Json.JsonElement";

    public static string Emit(Project project)
    {
        var w = new SourceWriter();
        w.Line("// <auto-generated>");
        w.Line("// Generated by Oriel.Generators from the [Service] classes of this project. Do not edit.");
        w.Line("// </auto-generated>");
        w.Line("#nullable enable");
        w.Line("#pragma warning disable");
        w.Line();
        using (w.Block("namespace Oriel.Generated"))
        {
            Module(w, project);
            foreach (var service in project.Services)
            {
                w.Line();
                Dispatcher(w, service);
            }
            w.Line();
            Codecs(w, project);
        }
        return w.ToString();
    }

    private static void Module(SourceWriter w, Project project)
    {
        w.Line("/// <summary>Registers the services of this assembly with Oriel as it loads.</summary>");
        using (w.Block("internal static class OrielModule"))
        {
            w.Line("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            using (w.Block("internal static void Initialize()"))
            {
                foreach (var service in project.Services)
                    w.Line($"global::Oriel.Generated.ServiceRegistry.Register<{service.CSharp}>(static service => new {DispatcherName(service)}(service));");
            }
        }
    }

    private static string DispatcherName(ServiceDef service) => Names.Identifier(service.CSharp.Replace("global::", "")) + "_Dispatcher";

    private static void Dispatcher(SourceWriter w, ServiceDef service)
    {
        var name = DispatcherName(service);
        using (w.Block($"file sealed class {name} : global::Oriel.Generated.ServiceDispatcher"))
        {
            w.Line($"private readonly {service.CSharp} _service;");
            w.Line();
            using (w.Block($"public {name}({service.CSharp} service) : base({Names.Literal(service.Name)})"))
                w.Line("_service = service;");
            w.Line();
            using (w.Block($"public override async global::System.Threading.Tasks.ValueTask<global::Oriel.Generated.ValueWriter?> InvokeAsync(string method, {Element} args, global::Oriel.Generated.CallContext context)"))
            using (w.Block("switch (method)"))
            {
                foreach (var method in service.Methods)
                {
                    using (w.Block($"case {Names.Literal(method.CSharp)}:"))
                        Invocation(w, service, method);
                }
                w.Line("default:");
                using (w.Indent())
                    w.Line($"throw new global::Oriel.Generated.MethodNotFoundException({Names.Literal(service.Name)}, method);");
            }
        }
    }

    /// <summary>Reads the arguments, calls the method, and returns the writer of its result.</summary>
    private static void Invocation(SourceWriter w, ServiceDef service, MethodDef method)
    {
        var page = method.Params.Where(p => p.Type is not null).ToList();
        var min = page.TakeWhile(p => !p.IsOptional).Count();
        w.Line($"global::Oriel.Generated.Arguments.Count(args, {Names.Literal(service.Name + "." + method.CSharp)}, {min}, {page.Count});");
        for (var i = 0; i < page.Count; i++)
        {
            var p = page[i];
            var read = ReadFunction(p.Type!, 0);
            w.Line(p.Default is null
                ? $"var a{i} = global::Oriel.Generated.Arguments.Read<{p.Type!.CSharp}>(args, {i}, {Names.Literal(p.Name)}, {read});"
                : $"var a{i} = global::Oriel.Generated.Arguments.ReadOptional<{p.Type!.CSharp}>(args, {i}, {Names.Literal(p.Name)}, {read}, {p.Default}, nullable: {(IsNullable(p.Type) ? "true" : "false")});");
        }

        var arguments = method.Params.Select(p => $"@{p.Name}: {p.Injected ?? "a" + page.IndexOf(p)}");
        Return(w, method, $"_service.@{method.CSharp}({string.Join(", ", arguments)})");
    }

    private static void Return(SourceWriter w, MethodDef method, string call)
    {
        switch (method.Returns)
        {
            case Returns.Void:
                w.Line($"{call};");
                w.Line("return null;");
                break;
            case Returns.Task:
                w.Line($"await {call}.ConfigureAwait(false);");
                w.Line("return null;");
                break;
            case Returns.Value:
                w.Line($"var result = {call};");
                w.Line($"return writer => {{ {WriteStatement(method.Result!, "writer", "result", 0)} }};");
                break;
            case Returns.TaskOfValue:
                w.Line($"var result = await {call}.ConfigureAwait(false);");
                w.Line($"return writer => {{ {WriteStatement(method.Result!, "writer", "result", 0)} }};");
                break;
        }
    }

    private static void Codecs(SourceWriter w, Project project)
    {
        w.Line("/// <summary>The JSON of the enums and objects the services use.</summary>");
        using (w.Block("file static class Codecs"))
        {
            foreach (var e in project.Enums)
            {
                EnumCodec(w, e);
                w.Line();
            }
            foreach (var o in project.Objects)
            {
                ObjectCodec(w, o);
                w.Line();
            }
        }
    }

    private static void EnumCodec(SourceWriter w, EnumDef e)
    {
        using (w.Block($"public static void Write_{e.Id}({Writer} writer, {e.CSharp} value)"))
        using (w.Block("writer.WriteStringValue(value switch", "});"))
        {
            foreach (var m in e.Members)
                w.Line($"{e.CSharp}.@{m.CSharp} => {Names.Literal(m.Json)},");
            w.Line($"_ => throw new global::System.ArgumentOutOfRangeException(nameof(value), value, {Names.Literal($"not a member of {e.TypeScript}")}),");
        }
        w.Line();

        var expected = string.Join(", ", e.Members.Select(m => "\"" + m.Json + "\""));
        using (w.Block($"public static {e.CSharp} Read_{e.Id}({Element} e)"))
        using (w.Block($"return {Json}.ReadString(e) switch", "};"))
        {
            foreach (var m in e.Members)
                w.Line($"{Names.Literal(m.Json)} => {e.CSharp}.@{m.CSharp},");
            w.Line($"var other => throw new global::Oriel.Generated.CodecException(\"\\\"\" + other + {Names.Literal($"\" is not a {e.TypeScript}: expected one of {expected}")}),");
        }
    }

    private static void ObjectCodec(SourceWriter w, ObjectDef o)
    {
        using (w.Block($"public static void Write_{o.Id}({Writer} writer, {o.CSharp} value)"))
        {
            if (!o.IsValueType)
            {
                using (w.Block("if (value is null)"))
                {
                    w.Line("writer.WriteNullValue();");
                    w.Line("return;");
                }
            }
            w.Line("writer.WriteStartObject();");
            foreach (var p in o.Properties)
            {
                w.Line($"writer.WritePropertyName({Names.Literal(p.Json)});");
                w.Line(WriteStatement(p.Type, "writer", $"value.@{p.CSharp}", 0));
            }
            w.Line("writer.WriteEndObject();");
        }
        w.Line();

        using (w.Block($"public static {o.CSharp} Read_{o.Id}({Element} e)"))
        {
            w.Line($"{Json}.ExpectObject(e);");
            var arguments = new List<string>();
            for (var i = 0; i < o.Constructor.Count; i++)
            {
                var c = o.Constructor[i];
                var p = o.Properties[c.Property];
                var fallback = c.Default ?? (IsNullable(p.Type) ? "default" : $"throw {Json}.Missing({Names.Literal(p.Json)})");
                w.Line($"var c{i} = {TryRead(p, $"p{i}")} ? p{i} : {fallback};");
                arguments.Add($"c{i}");
            }
            w.Line(o.UnsafeConstructor
                ? $"var value = Create_{o.Id}({string.Join(", ", arguments)});"
                : $"var value = new {o.CSharp}({string.Join(", ", arguments)});");

            for (var i = 0; i < o.Properties.Count; i++)
            {
                var p = o.Properties[i];
                var v = $"v{i}";
                var assign = p.Assign switch
                {
                    Assign.Setter => $"value.@{p.CSharp} = {v};",
                    Assign.Accessor => $"Set_{o.Id}_{p.CSharp}({(o.IsValueType ? "ref " : "")}value, {v});",
                    _ => null,
                };
                if (assign is null)
                    continue;
                w.Line($"if ({TryRead(p, v)}) {assign}");
                if (p.IsRequired)
                {
                    using (w.Indent())
                        w.Line($"else throw {Json}.Missing({Names.Literal(p.Json)});");
                }
            }
            w.Line("return value;");
        }

        // Members C# keeps us from setting, set without reflection.
        if (o.UnsafeConstructor)
        {
            w.Line();
            w.Line("[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Constructor)]");
            var parameters = o.Constructor.Select((c, i) => $"{c.Declared} c{i}");
            w.Line($"private static extern {o.CSharp} Create_{o.Id}({string.Join(", ", parameters)});");
        }
        foreach (var p in o.Properties.Where(p => p.Assign == Assign.Accessor))
        {
            w.Line();
            w.Line($"[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = {Names.Literal("set_" + p.CSharp)})]");
            w.Line($"private static extern void Set_{o.Id}_{p.CSharp}({(o.IsValueType ? "ref " : "")}{o.CSharp} value, {p.Declared} v);");
        }
    }

    private static string TryRead(PropertyDef p, string into) =>
        $"{Json}.TryReadProperty<{p.Type.CSharp}>(e, {Names.Literal(p.Json)}, {ReadFunction(p.Type, 0)}, out var {into})";

    private static bool IsNullable(TypeRef t) => t.Kind is TypeKind.NullableValue or TypeKind.NullableReference;

    /// <summary>An expression of type <c>Func&lt;JsonElement, T&gt;</c> that reads <paramref name="t"/>.</summary>
    private static string ReadFunction(TypeRef t, int depth) => t.Kind switch
    {
        TypeKind.Primitive => $"{Json}.Read{t.Name}",
        TypeKind.Enum or TypeKind.Object => $"Codecs.Read_{t.Name}",
        _ => $"static x{depth} => {ReadExpression(t, "x" + depth, depth + 1)}",
    };

    /// <summary>An expression that reads <paramref name="t"/> from the element <paramref name="e"/>.</summary>
    private static string ReadExpression(TypeRef t, string e, int depth) => t.Kind switch
    {
        TypeKind.Primitive or TypeKind.Enum or TypeKind.Object => $"{ReadFunction(t, depth)}({e})",
        TypeKind.NullableValue or TypeKind.NullableReference =>
            $"({Json}.IsNull({e}) ? default({t.CSharp}) : {ReadExpression(t.Element!, e, depth)})",
        TypeKind.Array => $"{Json}.ReadArray<{t.Element!.CSharp}>({e}, {ReadFunction(t.Element!, depth)})",
        TypeKind.List => $"{Json}.ReadList<{t.Element!.CSharp}>({e}, {ReadFunction(t.Element!, depth)})",
        TypeKind.Dictionary => $"{Json}.ReadDictionary<{t.Element!.CSharp}>({e}, {ReadFunction(t.Element!, depth)})",
        _ => throw new ArgumentOutOfRangeException(nameof(t)),
    };

    /// <summary>A statement that writes the value <paramref name="v"/> of type <paramref name="t"/>.</summary>
    private static string WriteStatement(TypeRef t, string w, string v, int depth) => t.Kind switch
    {
        TypeKind.Primitive => $"{Json}.Write({w}, {v});",
        TypeKind.Enum or TypeKind.Object => $"Codecs.Write_{t.Name}({w}, {v});",
        TypeKind.NullableValue or TypeKind.NullableReference =>
            $"if ({v} is {{ }} n{depth}) {{ {WriteStatement(t.Element!, w, "n" + depth, depth + 1)} }} else {w}.WriteNullValue();",
        TypeKind.Array or TypeKind.List =>
            $"{Json}.WriteArray<{t.Element!.CSharp}>({w}, {v}, {WriteFunction(t.Element!, depth)});",
        TypeKind.Dictionary =>
            $"{Json}.WriteDictionary<{t.Element!.CSharp}>({w}, {v}, {WriteFunction(t.Element!, depth)});",
        _ => throw new ArgumentOutOfRangeException(nameof(t)),
    };

    private static string WriteFunction(TypeRef t, int depth) =>
        $"static (w{depth}, v{depth}) => {{ {WriteStatement(t, "w" + depth, "v" + depth, depth + 1)} }}";
}
