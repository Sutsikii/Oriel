using System.Collections.Concurrent;
using System.ComponentModel;
using System.Diagnostics.CodeAnalysis;
using System.Reflection;
using System.Text;

namespace Oriel;

/// <summary>
/// The TypeScript clients the source generator wrote: one per assembly with
/// <see cref="ServiceAttribute"/> classes, registered as the assembly loads.
/// </summary>
public static class TypeScriptClient
{
    private static readonly ConcurrentDictionary<Assembly, string> s_sources = new();

    /// <summary>Records the client of <paramref name="assembly"/>. Generated code calls it.</summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public static void Register(Assembly assembly, string source)
    {
        ArgumentNullException.ThrowIfNull(assembly);
        ArgumentNullException.ThrowIfNull(source);
        s_sources[assembly] = source;
    }

    /// <summary>The client of the services of <paramref name="assembly"/>, or null when it has none.</summary>
    [Experimental(Experiments.TypeScriptClients, UrlFormat = Experiments.Url)]
    public static string? For(Assembly assembly) =>
        s_sources.TryGetValue(assembly, out var source) ? source : null;

    /// <summary>The names every client exports, which an index exports once.</summary>
    private static readonly HashSet<string> s_shared = ["CallError", "onFilesDropped"];

    /// <summary>
    /// The assembly's own client, and those of the assemblies it references,
    /// directly or not: its services', and those of the libraries it binds.
    /// Assemblies of .NET, and Oriel's, are skipped.
    /// </summary>
    [UnconditionalSuppressMessage("Trimming", "IL2026", Justification = "The build writes clients by running the app as built, never trimmed.")]
    internal static List<(string Name, string Source)> Clients(Assembly entry)
    {
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var clients = new List<(string, string)>();
        var queue = new Queue<Assembly>([entry]);
        seen.Add(entry.GetName().Name!);
        while (queue.Count > 0)
        {
            var assembly = queue.Dequeue();
            // Generated code registers the client as its module loads.
            System.Runtime.CompilerServices.RuntimeHelpers.RunModuleConstructor(assembly.ManifestModule.ModuleHandle);
            if (For(assembly) is { } source)
                clients.Add((assembly.GetName().Name!, source));
            foreach (var reference in assembly.GetReferencedAssemblies())
            {
                var name = reference.Name!;
                if (name.StartsWith("System", StringComparison.Ordinal) || name.StartsWith("Microsoft.", StringComparison.Ordinal)
                    || name is "mscorlib" or "netstandard" or "Oriel" || !seen.Add(name))
                    continue;
                try
                {
                    queue.Enqueue(Assembly.Load(reference));
                }
                catch (Exception e) when (e is FileNotFoundException or FileLoadException or BadImageFormatException)
                {
                    // not shipped with the app
                }
            }
        }
        return clients;
    }

    /// <summary>
    /// The files of <paramref name="clients"/> at <paramref name="path"/>: the
    /// one client there when there is one; else an index there re-exporting
    /// a module per assembly, in a folder of the index's name beside it.
    /// </summary>
    /// <returns>The files, by full path.</returns>
    /// <exception cref="InvalidOperationException">Two assemblies export the same name.</exception>
    internal static Dictionary<string, string> Files(IReadOnlyList<(string Name, string Source)> clients, string path)
    {
        var full = Path.GetFullPath(path);
        if (clients.Count == 1)
            return new() { [full] = clients[0].Source };

        var folderName = Path.GetFileNameWithoutExtension(full);
        var folder = Path.Combine(Path.GetDirectoryName(full)!, folderName);
        var files = new Dictionary<string, string>();
        var owners = new Dictionary<string, string>(StringComparer.Ordinal);
        var index = new StringBuilder();
        index.Append($"// Generated by Oriel: the clients of {string.Join(", ", clients.Select(c => c.Name))}. Do not edit.\n");
        var clashes = new List<string>();
        foreach (var (name, source) in clients)
        {
            var module = ModuleName(name);
            files[Path.Combine(folder, module + ".ts")] = source;
            var values = new List<string>();
            var types = new List<string>();
            foreach (var (export, isType) in Exports(source))
            {
                if (s_shared.Contains(export) && owners.ContainsKey(export))
                    continue; // the same in every client: exported once
                if (owners.TryGetValue(export, out var other))
                {
                    clashes.Add($"{export} (in {other} and {name})");
                    continue;
                }
                owners[export] = name;
                (isType ? types : values).Add(export);
            }
            var from = $"\"./{folderName}/{module}.js\"";
            if (values.Count > 0)
                index.Append($"export {{ {string.Join(", ", values)} }} from {from};\n");
            if (types.Count > 0)
                index.Append($"export type {{ {string.Join(", ", types)} }} from {from};\n");
        }
        if (clashes.Count > 0)
        {
            throw new InvalidOperationException(
                $"The TypeScript clients of several assemblies export the same names: {string.Join(", ", clashes)}. "
                + "Rename the services or types, or give a service another name with [Service(Name = ...)].");
        }
        files[full] = index.ToString();
        return files;
    }

    /// <summary>What a client exports, and whether each is a type only.</summary>
    internal static IEnumerable<(string Name, bool IsType)> Exports(string source)
    {
        foreach (var line in source.Split('\n'))
        {
            if (!line.StartsWith("export ", StringComparison.Ordinal))
                continue;
            var words = line.Split([' ', '<', '(', '=', '{', ':', ';'], StringSplitOptions.RemoveEmptyEntries);
            if (words.Length < 3)
                continue;
            switch (words[1])
            {
                case "const" or "function" or "class" or "let":
                    yield return (words[2], false);
                    break;
                case "type" or "interface":
                    // CallError is a type and a value of the same name: the value exports both.
                    if (!source.Contains($"export const {words[2]} ", StringComparison.Ordinal))
                        yield return (words[2], true);
                    break;
            }
        }
    }

    /// <summary>The file name of the module of an assembly: its name, with dots.</summary>
    private static string ModuleName(string assembly) =>
        new([.. assembly.Select(c => char.IsAsciiLetterOrDigit(c) || c is '.' or '-' or '_' ? c : '_')]);

    /// <summary>
    /// Writes the clients of <paramref name="entry"/> and the assemblies it
    /// references to <paramref name="path"/> (see <see cref="Files"/>). Each
    /// file is left untouched when it holds what it should; modules of
    /// assemblies that no longer have a client are removed.
    /// </summary>
    /// <exception cref="InvalidOperationException">No assembly has services, or two export the same name.</exception>
    internal static void WriteAll(Assembly entry, string path)
    {
        var clients = Clients(entry);
        if (clients.Count == 0)
            throw new InvalidOperationException($"{entry.GetName().Name} and the assemblies it references have no [Service] classes, so no TypeScript client.");
        var files = Files(clients, path);
        foreach (var (file, source) in files)
            WriteIfChanged(file, source);
        var folder = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(path))!, Path.GetFileNameWithoutExtension(path));
        if (Directory.Exists(folder))
        {
            foreach (var stale in Directory.GetFiles(folder, "*.ts").Where(f => !files.ContainsKey(f)))
            {
                if (File.ReadLines(stale).FirstOrDefault()?.StartsWith("// Generated by Oriel", StringComparison.Ordinal) == true)
                    File.Delete(stale);
            }
        }
    }

    private static bool WriteIfChanged(string full, string source)
    {
        if (File.Exists(full) && File.ReadAllText(full) == source)
            return false;
        Directory.CreateDirectory(Path.GetDirectoryName(full)!);
        File.WriteAllText(full, source, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        return true;
    }

    /// <summary>
    /// Writes the client of <paramref name="assembly"/> to <paramref name="path"/>,
    /// creating its directory. The file is left untouched when it already
    /// holds the client, so that dev servers watching it do not reload for nothing.
    /// </summary>
    /// <returns>Whether the file changed.</returns>
    /// <exception cref="InvalidOperationException">The assembly has no services.</exception>
    [Experimental(Experiments.TypeScriptClients, UrlFormat = Experiments.Url)]
    public static bool Write(Assembly assembly, string path)
    {
        var source = For(assembly)
            ?? throw new InvalidOperationException($"{assembly.GetName().Name} has no [Service] classes, so no TypeScript client.");
        return WriteIfChanged(Path.GetFullPath(path), source);
    }
}
